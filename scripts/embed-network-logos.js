/**
 * Embeds network logo PNGs as base64 so they ship inside the serverless bundle.
 * Run after generate-network-logos.js: node scripts/embed-network-logos.js
 */
const fs = require('fs');
const path = require('path');

const ASSETS_DIR = path.join(__dirname, '..', 'src', 'modules', 'whatsapp', 'assets', 'networks');
const OUT_FILE = path.join(__dirname, '..', 'src', 'modules', 'whatsapp', 'assets', 'network-logos.embedded.ts');

const FILES = [
  'data-network-banner.png',
  'mtn.png',
  'airtel.png',
  'glo.png',
  '9mobile.png',
  'data-mtn.png',
  'data-airtel.png',
  'data-glo.png',
  'data-9mobile.png',
];

const entries = FILES.map((name) => {
  const file = path.join(ASSETS_DIR, name);
  if (!fs.existsSync(file)) {
    throw new Error(`Missing asset: ${file}. Run generate-network-logos.js first.`);
  }
  const b64 = fs.readFileSync(file).toString('base64');
  let key = name.replace(/\.png$/, '').replace(/-/g, '_');
  if (/^[0-9]/.test(key)) key = `n_${key}`;
  return `  '${key}': '${b64}',`;
});

const content = `/* AUTO-GENERATED by scripts/embed-network-logos.js — do not edit by hand. */
export const NETWORK_LOGO_BASE64: Record<string, string> = {
${entries.join('\n')}
};

export function networkLogoDataUrl(name: string): string {
  let key = name.replace(/\\.png$/, '').replace(/-/g, '_');
  if (/^[0-9]/.test(key)) key = 'n_' + key;
  const b64 = NETWORK_LOGO_BASE64[key];
  if (!b64) throw new Error('Unknown network logo: ' + name);
  return 'data:image/png;base64,' + b64;
}
`;

fs.writeFileSync(OUT_FILE, content);
console.log(`Wrote ${OUT_FILE} (${content.length} bytes)`);
